export const FONT_NAMES = GOOGLE_FONTS.map(f => f.name)

/** CSS font-family value for a chosen family, with a sensible fallback stack. */
export function fontStack(name) {
  if (!name || name === 'System Default') return undefined
  const entry = GOOGLE_FONTS.find(f => f.name === name)
  const fallback = entry?.cat === 'Serif' ? 'serif'
    : entry?.cat === 'Monospace' ? 'monospace'
    : entry?.cat === 'Handwriting' ? 'cursive'
    : 'sans-serif'
  return `'${name}', ${fallback}`
}
