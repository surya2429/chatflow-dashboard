-- ============================================================================
-- 003_devices_and_calls.sql
-- Push-notification device registry, and call sessions for Website Chat
-- voice/video calling
-- ============================================================================

-- One row per app installation. An iOS install carries two tokens: the
-- regular APNs token (messages, assignments) and a PushKit VoIP token (incoming
-- calls — the only push type iOS lets wake a killed app straight into CallKit).
-- Android uses one FCM token for both; calls go as high-priority data messages.
CREATE TYPE push_platform AS ENUM ('ios', 'android');

CREATE TABLE devices (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id               UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- Stable per installation, generated by the app. Re-registering the same
  -- installation updates this row rather than accumulating stale tokens.
  device_id             VARCHAR(128) NOT NULL,
  platform              push_platform NOT NULL,
  push_token            TEXT,
  voip_token            TEXT,
  app_version           VARCHAR(32),
  -- Set when the provider reports the token dead (FCM UNREGISTERED, APNs 410)
  -- so we stop sending to it.
  disabled_at           TIMESTAMPTZ,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (device_id)
);

CREATE INDEX idx_devices_user ON devices (user_id) WHERE disabled_at IS NULL;

CREATE TRIGGER trg_devices_updated_at BEFORE UPDATE ON devices
  FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

-- ── CALL SESSIONS ────────────────────────────────────────────────────────
-- The signaling server is still a relay, but it now watches the call-control
-- messages go past so that a call has one authoritative record: who rang whom,
-- whether it was answered, and for how long. The outcome is written into the
-- conversation thread from here — once — instead of by whichever client
-- happened to notice, which could log it twice or (if the app was killed)
-- not at all.
CREATE TYPE call_state AS ENUM ('ringing', 'accepted', 'connected', 'ended');

CREATE TABLE call_sessions (
  id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  conversation_id       UUID NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
  direction             VARCHAR(8) NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  video                 BOOLEAN NOT NULL DEFAULT false,
  state                 call_state NOT NULL DEFAULT 'ringing',
  agent_id              UUID REFERENCES users (id) ON DELETE SET NULL,
  end_reason            VARCHAR(32),
  started_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  answered_at           TIMESTAMPTZ,
  ended_at              TIMESTAMPTZ
);

-- At most one live call per conversation — the relay only ever pairs one
-- agent with one visitor in a room.
CREATE UNIQUE INDEX uq_call_sessions_live ON call_sessions (conversation_id) WHERE state <> 'ended';
